-- Bảng giao dịch của KÊNH. Không có cột số dư: số dư chỉ nằm ở core.
-- Cú pháp chạy được trên cả Oracle 12c+ và H2 (MODE=Oracle).
CREATE TABLE teller_txn (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_ref             VARCHAR2(30)  NOT NULL,   -- mã tham chiếu gửi sang core
    idempotency_key     VARCHAR2(64)  NOT NULL,   -- key client gửi kèm khi tạo
    txn_type            VARCHAR2(20)  NOT NULL,   -- DEPOSIT / WITHDRAWAL
    account_no          VARCHAR2(20)  NOT NULL,
    amount              NUMBER(19,2)  NOT NULL,
    currency            VARCHAR2(3)   NOT NULL,
    description         VARCHAR2(255),
    status              VARCHAR2(20)  NOT NULL,
    maker_id            VARCHAR2(50)  NOT NULL,
    checker_id          VARCHAR2(50),
    reject_reason       VARCHAR2(255),
    core_posting_id     VARCHAR2(50),
    core_error_code     VARCHAR2(50),
    core_error_message  VARCHAR2(500),
    reconcile_attempts  NUMBER(5)     DEFAULT 0 NOT NULL,
    created_at          TIMESTAMP     NOT NULL,
    updated_at          TIMESTAMP     NOT NULL,
    submitted_at        TIMESTAMP,
    approved_at         TIMESTAMP,
    sent_to_core_at     TIMESTAMP,
    completed_at        TIMESTAMP,
    last_reconcile_at   TIMESTAMP,
    version             NUMBER(10)    DEFAULT 0 NOT NULL,  -- optimistic lock
    CONSTRAINT uk_teller_txn_ref  UNIQUE (txn_ref),
    CONSTRAINT uk_teller_txn_idem UNIQUE (idempotency_key),
    CONSTRAINT ck_teller_txn_amount CHECK (amount > 0)
);

-- Job đối soát tìm theo trạng thái + thời điểm gửi core
CREATE INDEX ix_teller_txn_status_sent ON teller_txn (status, sent_to_core_at);

-- Audit log: chỉ INSERT, không UPDATE/DELETE
CREATE TABLE txn_audit_log (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id          NUMBER(19)    NOT NULL,
    action          VARCHAR2(30)  NOT NULL,
    from_status     VARCHAR2(20),
    to_status       VARCHAR2(20)  NOT NULL,
    actor           VARCHAR2(50)  NOT NULL,
    detail          VARCHAR2(500),
    created_at      TIMESTAMP     NOT NULL,
    CONSTRAINT fk_audit_txn FOREIGN KEY (txn_id) REFERENCES teller_txn (id)
);

CREATE INDEX ix_audit_txn ON txn_audit_log (txn_id);
